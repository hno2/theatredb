"""Database maintenance: apply migrations, create revisions, show status or fully reset the database."""

import argparse
import sys

from alembic import command
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import text

from backend import user_management


def _migrate(_: argparse.Namespace) -> int:
    user_management.init_db()
    print("Database is at the latest migration.")
    return 0


def _revision(args: argparse.Namespace) -> int:
    with user_management._get_engine().connect() as connection:
        config = user_management.alembic_config(connection)
        if (
            MigrationContext.configure(connection).get_current_revision()
            != ScriptDirectory.from_config(config).get_current_head()
        ):
            print("Database is not at head; run `migrate` first.", file=sys.stderr)
            return 1

        def skip_empty(_context: object, _revision: object, directives: list) -> None:
            if directives[0].upgrade_ops.is_empty():
                directives.clear()
                print("No model changes detected; no revision created.")

        command.revision(config, message=args.message, autogenerate=True, process_revision_directives=skip_empty)
    return 0


def _status(_: argparse.Namespace) -> int:
    with user_management._get_engine().connect() as connection:
        config = user_management.alembic_config(connection)
        current = MigrationContext.configure(connection).get_current_revision()
        head = ScriptDirectory.from_config(config).get_current_head()
        print(f"current: {current or '-'}\nhead:    {head}")
        if current != head:
            print("Pending migrations; run `migrate`.")
            return 1
        try:
            command.check(config)
        except AutogenerateDiffsDetected as diffs:
            print(f"Models differ from migrations; run `revision -m ...`.\n{diffs}")
            return 1
    return 0


def _reset(args: argparse.Namespace) -> int:
    engine = user_management._get_engine()
    if engine.dialect.name != "postgresql":
        print("Reset supports PostgreSQL only.", file=sys.stderr)
        return 1
    name = engine.url.database
    target = engine.url.render_as_string(hide_password=True)
    if not args.yes:
        print(f"This permanently deletes ALL data (tables, crawl queue, migration state) in {target}.")
        if input(f'Type the database name "{name}" to confirm: ').strip() != name:
            print("Aborted; nothing changed.")
            return 1
    with engine.begin() as connection:
        connection.execute(text("DROP SCHEMA public CASCADE"))
        connection.execute(text("CREATE SCHEMA public"))
    user_management.init_db()
    print(f"Reset {name}; schema recreated at the latest migration.")
    return 0


def main(argv: list[str] | None = None) -> int:
    """Run one database maintenance command."""
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(required=True)
    commands.add_parser("migrate", help="Create the database if missing and apply pending migrations").set_defaults(
        run=_migrate
    )
    revision = commands.add_parser("revision", help="Autogenerate a migration from model changes")
    revision.add_argument("-m", "--message", required=True)
    revision.set_defaults(run=_revision)
    commands.add_parser("status", help="Show migration state and model drift").set_defaults(run=_status)
    reset = commands.add_parser("reset", help="Drop all data and recreate the schema")
    reset.add_argument("--yes", action="store_true", help="Skip the confirmation prompt")
    reset.set_defaults(run=_reset)
    args = parser.parse_args(argv)
    return args.run(args)


if __name__ == "__main__":
    sys.exit(main())
